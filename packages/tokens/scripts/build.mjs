#!/usr/bin/env node
/**
 * Design-token build — the single source of truth for the portal (CSS/Tailwind/JS) and the
 * mobile app (Dart). Reads W3C DTCG JSON from ../src, resolves {references}, enforces WCAG AA on
 * every semantic text/icon/border pair in BOTH themes (exits non-zero on any miss), then emits:
 *
 *   dist/tokens.css      CSS custom properties (--zona-*), light on :root/.light, dark on .dark
 *   dist/tailwind.css    Tailwind v4 @theme mapping (default palette removed → only tokens exist)
 *   dist/index.js/.d.ts  Resolved values + contrast report for JS (charts, maps, docs page)
 *   apps/mobile/lib/design_system/generated/zona_tokens.g.dart   ThemeExtensions for Flutter
 *
 * No dependencies on purpose: the token format is small and the multi-theme output is easier to
 * reason about in ~300 lines than through a generator's plugin config.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const repo = join(pkg, '..', '..');
const read = (f) => JSON.parse(readFileSync(join(pkg, 'src', f), 'utf8'));
const HEADER = 'GENERATED by packages/tokens/scripts/build.mjs from packages/tokens/src — do not edit by hand.';

// ---------------------------------------------------------------------------------------------
// Load, flatten, resolve
// ---------------------------------------------------------------------------------------------
function flatten(node, path = [], inheritedType, out = new Map()) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const type = child.$type ?? inheritedType;
    if (child && typeof child === 'object' && '$value' in child) {
      out.set([...path, key].join('.'), { value: child.$value, type, description: child.$description });
    } else if (child && typeof child === 'object') {
      flatten(child, [...path, key], type, out);
    }
  }
  return out;
}

function resolver(map) {
  const resolve = (value, seen = []) => {
    if (typeof value === 'string') {
      const m = value.match(/^\{([^}]+)\}$/);
      if (!m) return value;
      if (seen.includes(m[1])) throw new Error(`Circular token reference: ${[...seen, m[1]].join(' → ')}`);
      const target = map.get(m[1]);
      if (!target) throw new Error(`Unknown token reference {${m[1]}}`);
      return resolve(target.value, [...seen, m[1]]);
    }
    if (Array.isArray(value)) return value.map((v) => resolve(v, seen));
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, seen)]));
    return value;
  };
  return resolve;
}

const primitives = flatten(read('primitives.json'));
const core = flatten(read('core.json'));
const themes = {};
for (const name of ['light', 'dark']) {
  const semantic = flatten(read(`theme.${name}.json`));
  const all = new Map([...primitives, ...core, ...semantic]);
  const resolve = resolver(all);
  themes[name] = new Map([...semantic].map(([k, t]) => [k, { ...t, value: resolve(t.value) }]));
}
const coreResolved = new Map([...core].map(([k, t]) => [k, { ...t, value: resolver(core)(t.value) }]));

// ---------------------------------------------------------------------------------------------
// WCAG contrast gate
// ---------------------------------------------------------------------------------------------
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const luminance = (hex) => {
  const n = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => lin(parseInt(n.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const STATUSES = ['present', 'late', 'absent', 'suspected_fake', 'confirmed_fake', 'on_leave', 'info'];
function contrastPairs() {
  const p = [];
  const TEXT = 4.5, UI = 3;
  for (const s of ['canvas', 'surface', 'raised', 'overlay', 'sunken']) {
    p.push(['fg', s, TEXT, 'Body text'], ['fg-muted', s, TEXT, 'Secondary text']);
  }
  for (const s of ['canvas', 'surface', 'raised']) {
    p.push(['brand-fg', s, TEXT, 'Links / brand text'], ['accent-fg', s, TEXT, 'Accent text'],
      ['line-strong', s, UI, 'Input borders'], ['focus', s, UI, 'Focus ring'], ['accent', s, UI, 'Accent icon']);
  }
  p.push(['on-brand', 'brand', TEXT, 'Primary button'], ['on-brand', 'brand-hover', TEXT, 'Primary button hover'],
    ['on-accent', 'accent-strong', TEXT, 'Accent button'], ['on-accent', 'accent-hover', TEXT, 'Accent button hover'],
    ['brand-fg', 'brand-subtle', TEXT, 'Selected nav item'], ['fg', 'brand-subtle', TEXT, 'Text on selection'],
    ['accent-fg', 'accent-subtle', TEXT, 'Accent tint'], ['map.label', 'map.land', TEXT, 'Map labels']);
  for (const st of STATUSES) {
    const k = (part) => `status.${st}.${part}`;
    p.push([k('fg'), k('bg'), TEXT, `${st} chip`], [k('fg'), 'surface', TEXT, `${st} text`], [k('fg'), 'raised', TEXT, `${st} text (raised)`],
      [k('border'), 'surface', UI, `${st} border`], ['on-solid', k('solid'), TEXT, `${st} solid fill`],
      [k('solid'), 'surface', UI, `${st} marker`], [k('solid'), 'map.land', UI, `${st} marker on map`]);
  }
  return p;
}

const report = [];
for (const [theme, map] of Object.entries(themes)) {
  for (const [fgKey, bgKey, min, use] of contrastPairs()) {
    const fg = map.get(`color.${fgKey}`)?.value;
    const bg = map.get(`color.${bgKey}`)?.value;
    if (!fg || !bg) throw new Error(`Contrast pair references a missing token: ${fgKey} / ${bgKey} (${theme})`);
    const r = ratio(fg, bg);
    report.push({ theme, fg: fgKey, bg: bgKey, fgHex: fg, bgHex: bg, ratio: Math.round(r * 100) / 100, min, use, pass: r >= min });
  }
}
const failures = report.filter((r) => !r.pass);
if (failures.length) {
  console.error('\n✖ WCAG AA contrast failures:');
  for (const f of failures) console.error(`  [${f.theme}] ${f.fg} ${f.fgHex} on ${f.bg} ${f.bgHex} = ${f.ratio} (needs ${f.min}) — ${f.use}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------------------------
const cssName = (path) => `--zona-${path.replaceAll('.', '-').replaceAll('_', '-')}`;
const px = (v) => parseFloat(v);
const rem = (n) => `${+(n / 16).toFixed(4)}rem`;
const shadowCss = (layers) => layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${l.color}`).join(', ');
const bezier = (b) => `cubic-bezier(${b.join(', ')})`;
const fontStack = (fam) => fam.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
const camel = (s) => s.replace(/[-_.]([a-z0-9])/g, (_, c) => c.toUpperCase());
const by = (map, prefix) => [...map].filter(([k]) => k.startsWith(prefix));
const typeTokens = by(coreResolved, 'type.').map(([k, t]) => [k.slice(5), t.value]);

// ---------------------------------------------------------------------------------------------
// CSS
// ---------------------------------------------------------------------------------------------
function themeBlock(map) {
  const lines = [];
  for (const [k, t] of map) {
    if (t.type === 'color') lines.push(`  ${cssName(k)}: ${t.value};`);
    if (t.type === 'shadow') lines.push(`  ${cssName(k)}: ${shadowCss(t.value)};`);
  }
  return lines.join('\n');
}

const coreLines = [];
for (const [k, t] of coreResolved) {
  if (k.startsWith('space.')) coreLines.push(`  ${cssName(k)}: ${rem(px(t.value))};`);
  else if (k.startsWith('radius.')) coreLines.push(`  ${cssName(k)}: ${t.value};`);
  else if (k.startsWith('size.')) coreLines.push(`  ${cssName(k)}: ${k.startsWith('size.icon') ? t.value : rem(px(t.value))};`);
  else if (k.startsWith('font.family.')) coreLines.push(`  ${cssName(k)}: ${fontStack(t.value)};`);
  else if (k.startsWith('font.weight.')) coreLines.push(`  ${cssName(k)}: ${t.value};`);
  else if (k.startsWith('motion.duration.')) coreLines.push(`  ${cssName(k)}: ${t.value};`);
  else if (k.startsWith('motion.easing.')) coreLines.push(`  ${cssName(k)}: ${bezier(t.value)};`);
}
coreLines.push(`  --zona-font-sans: var(--zona-font-family-latin), var(--zona-font-family-arabic), system-ui, sans-serif;`);
const typeLatin = typeTokens.flatMap(([n, v]) => [
  `  --zona-type-${n}-size: ${rem(v.size)};`,
  `  --zona-type-${n}-weight: ${v.weight};`,
  `  --zona-type-${n}-lh: ${+(v.lineHeight / v.size).toFixed(4)};`,
  `  --zona-type-${n}-tracking: ${v.tracking}em;`,
]);
const typeArabic = typeTokens.flatMap(([n, v]) => [
  `  --zona-type-${n}-lh: ${+(v.lineHeightArabic / v.size).toFixed(4)};`,
  `  --zona-type-${n}-tracking: 0em;`,
]);
const durations = by(coreResolved, 'motion.duration.').map(([k]) => `    ${cssName(k)}: 0ms;`);

const css = `/* ${HEADER} */

:root {
${coreLines.join('\n')}
}

/* Typography: Latin metrics by default; Arabic gets taller line-heights and never letter-spacing. */
:root,
:lang(en) {
${typeLatin.join('\n')}
}
:lang(ar) {
${typeArabic.join('\n')}
  letter-spacing: 0;
}

/* Reduced motion: every token duration collapses to 0, so transitions built on tokens disappear. */
@media (prefers-reduced-motion: reduce) {
  :root {
${durations.join('\n')}
  }
}

:root,
.light {
  color-scheme: light;
${themeBlock(themes.light)}
}

.dark {
  color-scheme: dark;
${themeBlock(themes.dark)}
}
`;

// ---------------------------------------------------------------------------------------------
// Tailwind v4 theme
// ---------------------------------------------------------------------------------------------
const colorUtil = (k) => k.replace(/^color\./, '').replaceAll('.', '-').replaceAll('_', '-');
const tw = [];
for (const [k, t] of themes.light) if (t.type === 'color') tw.push(`  --color-${colorUtil(k)}: var(${cssName(k)});`);
for (const [k] of by(themes.light, 'shadow.')) tw.push(`  --shadow-${k.slice(7)}: var(${cssName(k)});`);
for (const [k] of by(coreResolved, 'radius.')) tw.push(`  --radius-${k.slice(7)}: var(${cssName(k)});`);
for (const [n] of typeTokens) {
  tw.push(`  --text-${n}: var(--zona-type-${n}-size);`,
    `  --text-${n}--line-height: var(--zona-type-${n}-lh);`,
    `  --text-${n}--letter-spacing: var(--zona-type-${n}-tracking);`,
    `  --text-${n}--font-weight: var(--zona-type-${n}-weight);`);
}
for (const [k] of by(coreResolved, 'font.weight.')) tw.push(`  --font-weight-${k.slice(12)}: var(${cssName(k)});`);
for (const [k] of by(coreResolved, 'motion.easing.')) tw.push(`  --ease-${k.slice(14)}: var(${cssName(k)});`);
tw.push(`  --font-sans: var(--zona-font-sans);`);

const tailwind = `/* ${HEADER} */
/* Removes Tailwind's default palette, radii, shadows, type sizes and tracking so the ONLY values a
   component can use are design tokens (no hard-coded colours, no letter-spacing utilities). */
@theme {
  --color-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --text-*: initial;
  --tracking-*: initial;
  --leading-*: initial;
  --ease-*: initial;
  --spacing: 0.25rem;
}

@theme inline {
${tw.join('\n')}
}
`;

// ---------------------------------------------------------------------------------------------
// JS / TS
// ---------------------------------------------------------------------------------------------
const toObj = (map, strip = '') => {
  const o = {};
  for (const [k, t] of map) {
    const parts = k.slice(strip.length).split('.');
    let cur = o;
    parts.slice(0, -1).forEach((p) => (cur = cur[p] ??= {}));
    cur[parts.at(-1)] = t.value;
  }
  return o;
};
const jsData = {
  light: toObj(themes.light),
  dark: toObj(themes.dark),
  core: toObj(coreResolved),
  primitives: toObj(primitives).color,
  contrast: report,
};
const typeOf = (v, indent = '') => {
  if (Array.isArray(v)) return v.length && typeof v[0] === 'object' ? `Array<${typeOf(v[0], indent)}>` : `${typeof (v[0] ?? '')}[]`;
  if (v && typeof v === 'object') {
    const inner = Object.entries(v).map(([k, x]) => `${indent}  ${JSON.stringify(k)}: ${typeOf(x, indent + '  ')};`).join('\n');
    return `{\n${inner}\n${indent}}`;
  }
  return typeof v;
};
const js = `// ${HEADER}\n${Object.entries(jsData).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};`).join('\n\n')}\n`;
const dts = `// ${HEADER}\n${Object.entries(jsData).map(([k, v]) => `export declare const ${k}: ${k === 'contrast' ? 'Array<{ theme: "light" | "dark"; fg: string; bg: string; fgHex: string; bgHex: string; ratio: number; min: number; use: string; pass: boolean }>' : typeOf(v)};`).join('\n\n')}\n`;

// ---------------------------------------------------------------------------------------------
// Dart
// ---------------------------------------------------------------------------------------------
const dartColor = (v) => {
  if (v.startsWith('#')) return `Color(0xFF${v.slice(1).toUpperCase()})`;
  const m = v.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  if (!m) throw new Error(`Unsupported colour for Dart: ${v}`);
  const a = Math.round(parseFloat(m[4]) * 255).toString(16).padStart(2, '0');
  return `Color(0x${a}${[m[1], m[2], m[3]].map((n) => (+n).toString(16).padStart(2, '0')).join('')})`.toUpperCase().replace('COLOR(0X', 'Color(0x');
};
const colorKeys = [...themes.light].filter(([, t]) => t.type === 'color').map(([k]) => k);
const field = (k) => camel(k.replace(/^color\./, '').replaceAll('.', '_'));
const dartColorsInstance = (map) => colorKeys.map((k) => `    ${field(k)}: ${dartColor(map.get(k).value)},`).join('\n');
const shadowKeys = by(themes.light, 'shadow.').map(([k]) => k);
const dartShadows = (map) => shadowKeys.map((k) => `    ${camel(k.slice(7))}: [\n${map.get(k).value.map((l) =>
  `      BoxShadow(offset: Offset(${l.x}, ${l.y}), blurRadius: ${l.blur}, spreadRadius: ${l.spread}, color: ${dartColor(l.color)}),`).join('\n')}\n    ],`).join('\n');
const dartNum = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const spaceConsts = by(coreResolved, 'space.').map(([k, t]) => `  static const double s${k.slice(6)} = ${dartNum(px(t.value))};`).join('\n');
const radiusConsts = by(coreResolved, 'radius.').map(([k, t]) => `  static const double ${camel('r_' + k.slice(7)).replace(/^r/, '').replace(/^./, (c) => c.toLowerCase()).replace(/^(\d)/, 'x$1')} = ${dartNum(px(t.value))};`).join('\n');
const sizeConsts = by(coreResolved, 'size.').map(([k, t]) => `  static const double ${camel(k.slice(5))} = ${dartNum(px(t.value))};`).join('\n');
const motionConsts = [
  ...by(coreResolved, 'motion.duration.').map(([k, t]) => `  static const Duration ${k.slice(16)} = Duration(milliseconds: ${parseInt(t.value)});`),
  ...by(coreResolved, 'motion.easing.').map(([k, t]) => `  static const Cubic ${k.slice(14)} = Cubic(${t.value.map(dartNum).join(', ')});`),
].join('\n');
const typeConsts = typeTokens.map(([n, v]) => `  static const ${camel(n)} = ZonaTypeToken(size: ${dartNum(v.size)}, lineHeight: ${dartNum(v.lineHeight)}, lineHeightArabic: ${dartNum(v.lineHeightArabic)}, weight: FontWeight.w${v.weight}, trackingEm: ${dartNum(v.tracking)});`).join('\n');
const fam = (k) => coreResolved.get(k).value.find((f) => !/Variable/.test(f));
const statusDart = by(coreResolved, 'status.').map(([k, t]) => `  '${k.slice(7)}': (icon: '${t.value.icon}', label: '${t.value.label}'),`).join('\n');

const dart = `// ${HEADER}
// ignore_for_file: constant_identifier_names, public_member_api_docs
import 'package:flutter/material.dart';

/// Semantic colours. Read with \`ZonaColors.of(context)\`.
@immutable
class ZonaColors extends ThemeExtension<ZonaColors> {
  const ZonaColors({
${colorKeys.map((k) => `    required this.${field(k)},`).join('\n')}
  });

${colorKeys.map((k) => `  final Color ${field(k)};`).join('\n')}

  static const light = ZonaColors(
${dartColorsInstance(themes.light)}
  );

  static const dark = ZonaColors(
${dartColorsInstance(themes.dark)}
  );

  static ZonaColors of(BuildContext context) => Theme.of(context).extension<ZonaColors>()!;

  @override
  ZonaColors copyWith() => this;

  @override
  ZonaColors lerp(ThemeExtension<ZonaColors>? other, double t) {
    if (other is! ZonaColors) return this;
    return ZonaColors(
${colorKeys.map((k) => `      ${field(k)}: Color.lerp(${field(k)}, other.${field(k)}, t)!,`).join('\n')}
    );
  }
}

/// Elevation (shadow) per theme. Read with \`ZonaElevation.of(context)\`.
@immutable
class ZonaElevation extends ThemeExtension<ZonaElevation> {
  const ZonaElevation({${shadowKeys.map((k) => `required this.${camel(k.slice(7))}`).join(', ')}});

${shadowKeys.map((k) => `  final List<BoxShadow> ${camel(k.slice(7))};`).join('\n')}

  static const light = ZonaElevation(
${dartShadows(themes.light)}
  );

  static const dark = ZonaElevation(
${dartShadows(themes.dark)}
  );

  static ZonaElevation of(BuildContext context) => Theme.of(context).extension<ZonaElevation>()!;

  @override
  ZonaElevation copyWith() => this;

  @override
  ZonaElevation lerp(ThemeExtension<ZonaElevation>? other, double t) {
    if (other is! ZonaElevation) return this;
    return ZonaElevation(${shadowKeys.map((k) => `${camel(k.slice(7))}: BoxShadow.lerpList(${camel(k.slice(7))}, other.${camel(k.slice(7))}, t)!`).join(', ')});
  }
}

/// Spacing on a 4/8 scale (logical pixels).
abstract final class ZonaSpace {
${spaceConsts}
}

abstract final class ZonaRadius {
${radiusConsts}
}

abstract final class ZonaSize {
${sizeConsts}
}

abstract final class ZonaMotion {
${motionConsts}
}

abstract final class ZonaFonts {
  static const String latin = '${fam('font.family.latin')}';
  static const String arabic = '${fam('font.family.arabic')}';
}

@immutable
class ZonaTypeToken {
  const ZonaTypeToken({required this.size, required this.lineHeight, required this.lineHeightArabic, required this.weight, required this.trackingEm});
  final double size;
  final double lineHeight;
  final double lineHeightArabic;
  final FontWeight weight;
  final double trackingEm;
}

abstract final class ZonaType {
${typeConsts}
}

/// Attendance status metadata: Lucide icon name + i18n label key (status is never colour alone).
const Map<String, ({String icon, String label})> zonaStatusMeta = {
${statusDart}
};
`;

// ---------------------------------------------------------------------------------------------
// Write
// ---------------------------------------------------------------------------------------------
const write = (file, content) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
};
write(join(pkg, 'dist', 'tokens.css'), css);
write(join(pkg, 'dist', 'tailwind.css'), tailwind);
write(join(pkg, 'dist', 'index.js'), js);
write(join(pkg, 'dist', 'index.d.ts'), dts);
write(join(repo, 'apps', 'mobile', 'lib', 'design_system', 'generated', 'zona_tokens.g.dart'), dart);

const worst = (theme) => report.filter((r) => r.theme === theme).sort((a, b) => a.ratio / a.min - b.ratio / b.min)[0];
console.log(`✔ tokens built — ${report.length} contrast pairs checked, all pass WCAG AA`);
for (const t of ['light', 'dark']) {
  const w = worst(t);
  console.log(`  tightest ${t}: ${w.fg} on ${w.bg} = ${w.ratio}:1 (min ${w.min}) — ${w.use}`);
}
